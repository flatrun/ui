// Regenerates src/lib/logo-icons.ts from @iconify-json/logos.
//
// The published set is about 2,200 brand logos in one JSON object, so importing it would put
// all of them in the bundle. This writes out only the logos the app renders. Add a name
// below, run `node scripts/build-logo-icons.mjs`, and commit the result.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { icons, aliases = {}, width, height } = require("@iconify-json/logos/icons.json");

const used = [
  "nginx",
  "apache",
  "mysql-icon",
  "mariadb-icon",
  "postgresql",
  "redis",
  "mongodb-icon",
  "sqlite",
  "elasticsearch",
  "meilisearch",
  "memcached",
  "rabbitmq-icon",
  "kafka-icon",
  "nats-icon",
  "influxdb-icon",
  "couchdb-icon",
  "nodejs-icon",
  "bun",
  "deno",
  "python",
  "django-icon",
  "php",
  "laravel",
  "wordpress-icon",
  "ghost",
  "nextjs-icon",
  "nuxt-icon",
  "astro-icon",
  "svelte-icon",
  "vue",
  "react",
  "go",
  "rust",
  "java",
  "ruby",
  "rails",
  "grafana",
  "prometheus",
  "n8n",
  "valkey",
  "vault-icon",
  "consul",
  "strapi-icon",
  "supabase-icon",
  "hasura-icon",
  "docker-icon",
];

const missing = used.filter((name) => !icons[name] && !aliases[name]);
if (missing.length) {
  console.error(`These are not in the Logos set: ${missing.join(", ")}`);
  process.exit(1);
}

const resolve = (name) => icons[name] ?? { ...icons[aliases[name].parent], ...aliases[name] };
const subset = { prefix: "logos", width, height, icons: Object.fromEntries(used.map((n) => [n, resolve(n)])) };

writeFileSync(
  new URL("../src/lib/logo-icons.ts", import.meta.url),
  `// Generated by scripts/build-logo-icons.mjs. Do not edit by hand.
//
// Only the logos this app renders are here: importing the published set pulls every logo
// into the bundle.
export const logosSubset = ${JSON.stringify(subset, null, 2)} as const;
`,
);

console.log(`Wrote ${used.length} logos.`);
